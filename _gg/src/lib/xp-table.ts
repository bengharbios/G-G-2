// ذاكرة مؤقتة للجدول المُعدّل من الأدمن (يتم تحميلها من DB)
let _customXpTable: number[] | null = null;

export function getXpForLevel(level: number): number {
  // index 0 = XP from level 1→2, index 1 = XP from 2→3, etc.
  const table = _customXpTable || DEFAULT_XP_TABLE;
  if (level < 1) return 0;
  if (level >= table.length + 1) return table[table.length - 1]; // آخر قيمة لأي مستوى أعلى
  return table[level - 1] || 0;
}

export function getTotalXpForLevel(level: number): number {
  // مجموع XP المطلوب للوصول لمستوى معين (من المستوى 1)
  const table = _customXpTable || DEFAULT_XP_TABLE;
  let total = 0;
  for (let i = 0; i < Math.min(level - 1, table.length); i++) {
    total += table[i];
  }
  return total;
}

export function setCustomXpTable(table: number[] | null): void {
  _customXpTable = table;
}

export function getDefaultXpTable(): number[] {
  return [...DEFAULT_XP_TABLE];
}
